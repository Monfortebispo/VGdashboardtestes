const fs=require('fs'),path=require('path'),assert=require('assert');
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const model=read('src/modern/data/financials-model.ts');
const legacy=read('src/modern/data/legacy-data-sources.ts');
const costs=read('src/modern/data/costs-service.ts');
const usali=read('assets/js/modules/pl-usali-reconciliation-v46.js');
assert(model.includes('interface FinancialsSourceSnapshot'),'deve existir contrato financeiro tipado');
assert(model.includes('raw:unknown'),'snapshot financeiro deve preservar payload legado durante a migração');
assert(model.includes('canonicalFinancialValue'),'deve existir acesso canónico a métricas financeiras por hotel/ano');
assert(model.includes("canonicalFinancialTotal(value,hotels,'Receita Total',year)"),'Receita Total oficial deve ter um único accessor moderno');
assert(model.includes('reconcileUsaliRevenue'),'modelo financeiro deve expor reconciliação USALI testável');
assert(model.includes('other:legacyOther+residual'),'receita não classificada deve reconciliar em Outros Departamentos');
assert(legacy.includes("case'financials':return financialsSnapshot(w.RAW)"),'registry deve adaptar RAW para snapshot financeiro tipado');
assert(costs.includes("ensureDataSource<FinancialsSourceSnapshot>('financials'"),'custos deve consumir a fonte financeira tipada');
assert(costs.includes('costsSnapshot(financials.raw)'),'normalização de custos deve receber apenas o payload financeiro');
assert(usali.includes("['Receita Total']"),'bridge USALI deve continuar alinhada com Receita Total oficial durante a migração');
console.log('✓ Modern financials source: contrato tipado, totais canónicos e reconciliação USALI protegidos');
